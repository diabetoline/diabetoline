/** Sfatul zilei: același toată ziua, altul mâine; ciclul reia după ce s-au epuizat. */
export function tipOfDay(lang: Lang, now = Date.now()): string {
  const list = TIPS[lang] ?? TIPS.en;
  const day = Math.floor((now + new Date(now).getTimezoneOffset() * -60_000) / 86_400_000);
  return list[day % list.length];
}
